#' RAA general liability triangle
#'
#' Cumulative incurred losses (USD thousands) for automatic facultative
#' general liability business (excluding asbestos and environmental), from
#' the Reinsurance Association of America *Historical Loss Development Study*
#' (1991), as used in Mack (1993, 1994). Accident years 1981-1990,
#' development ages 1-10 years.
#'
#' @format A cumulative `triangle`, 10 x 10.
#' @source Mack, T. (1994). Measuring the variability of chain ladder reserve
#'   estimates. *CAS Forum*, Spring 1994. Values cross-checked against the
#'   `raa` sample in the Python `chainladder` package.
"raa"

#' Taylor and Ashe (1983) triangle
#'
#' Cumulative claims from Taylor and Ashe (1983), widely used in the
#' stochastic reserving literature (Mack 1993; England and Verrall 2002;
#' known as `GenIns` in the R ChainLadder package). Origin periods 1-10,
#' development ages 1-10.
#'
#' @format A cumulative `triangle`, 10 x 10. Measure is recorded as
#'   `"incurred"` for labelling.
#' @source Taylor, G. C. and Ashe, F. R. (1983). Second moments of estimates
#'   of outstanding claims. *Journal of Econometrics* 23, 37-61. Values
#'   cross-checked against the `genins` sample in Python `chainladder`.
"taylor_ashe"

#' Synthetic claim-level transactions
#'
#' Simulated claim transactions for accident years 2015-2024 valued at the
#' end of 2024. **Synthetic: does not represent any insurer's experience.**
#' Generated by `data-raw/make_data.R` with a fixed seed. Includes occasional
#' negative paid amounts (recoveries) and claims with no movement in some
#' years.
#'
#' @format A data.frame with columns `claim_id`, `accident_year`, `dev_age`
#'   (years, 1 = first year), `paid` (incremental paid) and `incurred`
#'   (incremental change in incurred).
"claims_synthetic"

#' Synthetic earned premium
#'
#' Earned premium matching [claims_synthetic]. **Synthetic.**
#'
#' @format A data.frame with `accident_year` and `earned_premium`.
"premium_synthetic"
